import Foundation

enum ViewScopeInterfaceLanguage: String, Hashable, CaseIterable {
    case english = "en"
    case simplifiedChinese = "zh-Hans"
    case traditionalChinese = "zh-Hant"

    init(identifier: String?) {
        guard let identifier = identifier?.trimmingCharacters(in: .whitespacesAndNewlines), !identifier.isEmpty else {
            self = .english
            return
        }

        let normalized = identifier.lowercased()
        if normalized.hasPrefix("zh-hant") || normalized.hasPrefix("zh-tw") || normalized.hasPrefix("zh-hk") || normalized.hasPrefix("zh-mo") {
            self = .traditionalChinese
        } else if normalized.hasPrefix("zh") {
            self = .simplifiedChinese
        } else {
            self = .english
        }
    }

    var locale: Locale {
        Locale(identifier: rawValue)
    }

    func text(_ key: String, _ arguments: CVarArg...) -> String {
        text(key, arguments: arguments)
    }

    func text(_ key: String, arguments: [CVarArg]) -> String {
        let format = Self.lookup(key, in: self) ?? Self.lookup(key, in: .english) ?? key
        guard arguments.isEmpty == false else {
            return format
        }
        return String(format: format, locale: locale, arguments: arguments)
    }

    /// 先查平台专属表（`platformTable`，由 AppKit / UIKit 目录各自提供），再查通用表。
    private static func lookup(_ key: String, in language: ViewScopeInterfaceLanguage) -> String? {
        if let value = platformTable[language]?[key] {
            return value
        }
        return table[language]?[key]
    }

